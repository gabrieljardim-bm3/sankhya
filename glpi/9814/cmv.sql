SELECT 
    CAB.NUNOTA,
    CAB.NUMNOTA,
    CAB.CODPROJ AS "PROJETO",
    CAB.AD_NROINVOICE AS "INVOICE", 
    CASE CAB.AD_TIPOCONTAINER 
        WHEN 1 THEN '20 Pés'
        WHEN 2 THEN '40 NOR'
        WHEN 3 THEN '40 HC'
        ELSE 'Não Informado'
    END AS "TIPO_CONTAINER",
    -- Capacidade prática segura adotada
    CASE CAB.AD_TIPOCONTAINER 
        WHEN 1 THEN 28.0
        WHEN 2 THEN 55.0
        WHEN 3 THEN 65.0
        ELSE 0.0
    END AS "CAPACIDADE_PRATICA_M3",
    -- Consolidação por função customizada
    NVL(GRUPOSOULPRD.AD_GET_M3(CAB.NUNOTA), 0) AS "CUBAGEM_PEDIDO_M3", 
    NVL(CAB.AD_QTDCONTAINER, 0) AS "QTD_CONTAINERS", 
    NVL(CAB.AD_VLRFRETECONTAINER, 0) AS "FRETE_POR_CONTAINER_USD", 
    -- Cálculo do aproveitamento real (%)
    CASE 
        WHEN CAB.AD_TIPOCONTAINER = 1 THEN ROUND((GRUPOSOULPRD.AD_GET_M3(CAB.NUNOTA) / 28.0) * 100, 2)
        WHEN CAB.AD_TIPOCONTAINER = 2 THEN ROUND((GRUPOSOULPRD.AD_GET_M3(CAB.NUNOTA) / 55.0) * 100, 2)
        WHEN CAB.AD_TIPOCONTAINER = 3 THEN ROUND((GRUPOSOULPRD.AD_GET_M3(CAB.NUNOTA) / 65.0) * 100, 2)
        ELSE 0.0
    END AS "APROVEITAMENTO_REAL_PERC"
FROM TGFCAB CAB
WHERE CAB.TIPMOV = 'C' -- Notas de Compra/Importação [14]
  AND CAB.STATUSNOTA = 'L' 
  AND CAB.AD_TIPOCONTAINER IS NOT NULL
  AND CAB.NUNOTA = 1482558;
  
  
  
  
